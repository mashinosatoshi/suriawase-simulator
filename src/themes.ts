export interface Theme {
  field: string;
  setting: string;
  topic: string;
  cast: string;
}

/** お題を 1 つ選ぶ。分野・舞台・話題・顔ぶれを、それぞれ一様に選ぶ */
export function pickTheme(rand: () => number = Math.random): Theme {
  const pick = (list: readonly string[]) => list[Math.floor(rand() * list.length)];
  const field = pick(Object.keys(THEME_SETTINGS));
  return { field, setting: pick(THEME_SETTINGS[field]), topic: pick(THEME_TOPICS), cast: pick(THEME_CASTS) };
}
